export async function seedCompleteCatalog() {
  try {
    if (mongoose.connection.readyState !== 1) {
      await connectDB();
    }
    console.log("🎮 Seeding Complete Anime & Gaming Database Catalog...");

    // Fetch existing categories for mapping
    const [animeCats, gameCats] = await Promise.all([
      AnimeCategory.find({}).lean(),
      GameCategory.find({}).lean(),
    ]);

    const animeCatMap = new Map(animeCats.map((c) => [c.slug, c._id]));
    const gameCatMap = new Map(gameCats.map((c) => [c.slug, c._id]));

    // Seed/Upsert Anime Titles
    let animeUpserted = 0;
    for (const anime of COMPLETE_ANIME_CATALOG) {
      const categoryIds = (anime.categorySlugs || [])
        .map((slug) => animeCatMap.get(slug))
        .filter(Boolean);

      await AnimeTitle.findOneAndUpdate(
        { title: anime.title },
        {
          $set: {
            title: anime.title,
            aliases: anime.aliases || [],
            image: anime.image || "",
            genres: anime.genres || [],
            year: anime.year,
            score: anime.score,
            categories: categoryIds,
            popularity: Math.floor(Math.random() * 1000) + 500,
          },
        },
        { upsert: true, new: true }
      );
      animeUpserted++;
    }
    console.log(`✅ Upserted ${animeUpserted} Anime Titles with Aliases into MongoDB!`);

    // Seed/Upsert Game Titles
    let gameUpserted = 0;
    for (const game of COMPLETE_GAME_CATALOG) {
      const categoryIds = (game.categorySlugs || [])
        .map((slug) => gameCatMap.get(slug))
        .filter(Boolean);

      await GameTitle.findOneAndUpdate(
        { title: game.title },
        {
          $set: {
            title: game.title,
            aliases: game.aliases || [],
            image: game.image || "",
            genres: game.genres || [],
            year: game.year,
            score: game.score,
            categories: categoryIds,
            popularity: Math.floor(Math.random() * 1000) + 500,
          },
        },
        { upsert: true, new: true }
      );
      gameUpserted++;
    }
    console.log(`✅ Upserted ${gameUpserted} Game Titles with Aliases into MongoDB!`);
    return { success: true, animeCount: animeUpserted, gameCount: gameUpserted };
  } catch (error) {
    console.error("❌ Catalog Seed Error:", error);
    throw error;
  }
}

// Auto-run if executed directly via node CLI
if (process.argv[1]?.endsWith("seedCompleteCatalog.js")) {
  seedCompleteCatalog()
    .then(() => process.exit(0))
    .catch(() => process.exit(1));
}
